function 표조각(text, x, y, size) {
  size = size || 10;
  var items = [], cx = x;
  text.split('').forEach(function (ch) {
    if (ch === ' ') { cx += size * 0.6; return; }
    items.push({ str: ch, width: size, transform: [size, 0, 0, size, cx, y] });
    cx += size + 0.4;
  });
  return items;
}

