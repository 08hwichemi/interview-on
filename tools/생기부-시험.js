// 「가운데」 셈으로 되짚을 수도 있지만, 칸이 다음 쪽으로 이어지면 그 셈이 깨져서
// 이어지는 쪽 맨 위(앞 칸 내용)에 다음 이름표가 붙습니다 —
// 동아리 내용이 진로활동으로 들어간 까닭입니다.
